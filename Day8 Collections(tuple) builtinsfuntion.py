# working with built in function

x = (1,4,6,3,8,9,6)
print(x)

print("\nMin : ",min(x))
print("\nMax : ",max(x))
print("\nlen : ",len(x))
print("\nsum : ",sum(x))
print("\nsorted : ",sorted(x))
print("\nreverse : ",tuple(reversed(x)))

print("\nworking with tuple class methods \n")

print("count of 6 in a tuple :  ",x.count(6))

print("index of 4 : ",x.index(4))
